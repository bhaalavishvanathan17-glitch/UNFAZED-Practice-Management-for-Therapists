const mongoose = require('mongoose');

const clinicalNoteSchema = new mongoose.Schema({
  therapistId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Therapist',
    required: [true, 'Therapist ID is required'],
    index: true,
  },
  clientId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Client',
    required: [true, 'Client ID is required'],
    index: true,
  },
  sessionId: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'Session',
    default: null,
    index: true,
  },
  noteType: {
    type: String,
    enum: ['soap', 'dap', 'freeform', 'consultation'],
    default: 'soap',
  },
  title: {
    type: String,
    required: [true, 'Note title is required'],
    trim: true,
    default: 'Clinical Progress Note',
  },
  visibility: {
    type: String,
    enum: ['private', 'shared'],
    default: 'private',
    required: true,
    index: true,
  },
  // Rich text generated by TipTap
  contentHtml: {
    type: String,
    default: '',
  },
  contentJson: {
    type: mongoose.Schema.Types.Mixed,
    default: null,
  },
  // Structured SOAP template fields
  soap: {
    subjective: { type: String, default: '' },
    objective: { type: String, default: '' },
    assessment: { type: String, default: '' },
    plan: { type: String, default: '' },
  },
  // Structured DAP template fields
  dap: {
    data: { type: String, default: '' },
    assessment: { type: String, default: '' },
    plan: { type: String, default: '' },
  },
  sessionDate: {
    type: Date,
    default: Date.now,
  },
  sharedAt: {
    type: Date,
    default: null,
  },
  isLocked: {
    type: Boolean,
    default: false,
  },
}, {
  timestamps: true,
});

// Compound index for querying client clinical timeline
clinicalNoteSchema.index({ therapistId: 1, clientId: 1, createdAt: -1 });
clinicalNoteSchema.index({ clientId: 1, visibility: 1 });

module.exports = mongoose.model('ClinicalNote', clinicalNoteSchema);
